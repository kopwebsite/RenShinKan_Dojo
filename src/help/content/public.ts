export function getPublicHelpCatalog(locale: Language): HelpCatalog {
  const topics =
    locale === "th" ? th : locale === "ja" ? ja : locale === "zh-CN" ? zh : en;
  return {
    audience: "public",
    locale,
    ui: helpUi(locale),
    articles: buildArticles("public", locale, topics.map(article)),
  };
}
