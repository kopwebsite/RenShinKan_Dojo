type Language = "en" | "th" | "ja" | "zh-CN";

type Topic = {
  id: string;
  category: HelpCategory;
  route: string;
  href: string;
  title: string;
  summary: string;
  steps: string[];
  action: string;
};

function article(topic: Topic): LocalizedArticle {
  return {
    id: topic.id,
    category: topic.category,
    routes: [topic.route],
    title: topic.title,
    summary: topic.summary,
    steps: topic.steps.map((instruction) => ({
      title: "",
      instruction,
      result: "",
    })),
    troubleshooting: [],
    related: [],
    keywords: `${topic.title} ${topic.summary}`
      .toLocaleLowerCase()
      .replace(/\*\*/g, "")
      .split(/\s+/),
    action: { label: topic.action, href: topic.href },
  };
}

