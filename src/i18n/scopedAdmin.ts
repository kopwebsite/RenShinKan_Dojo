const originals = new WeakMap<Node, string>();
const attributeOriginals = new WeakMap<Element, Map<string, string>>();
const attributes = ["aria-label", "title", "placeholder", "alt"] as const;

function localize(value: string, language: AdminLanguage) {
  if (language === "en") return value;
  const leading = value.match(/^\s*/)?.[0] || "";
  const trailing = value.match(/\s*$/)?.[0] || "";
  const core = value.trim();
  const translated = thaiPhrases[core] || translateEnglishLiteral(language, core);
  return translated ? `${leading}${translated}${trailing}` : value;
}

function isLocalizedVariant(source: string, value: string) {
  return (["en", "th"] as const).some((language) => localize(source, language) === value);
}

function translateTree(root: HTMLElement, language: AdminLanguage) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let node: Node | null;
  while ((node = walker.nextNode())) {
    if (node.parentElement?.closest("[data-no-translate], code, pre, script, style")) continue;
    const current = node.nodeValue || "";
    const previous = originals.get(node);
    if (previous === undefined || !isLocalizedVariant(previous, current)) {
      originals.set(node, current);
    }
    const translated = localize(originals.get(node) || "", language);
    if (node.nodeValue !== translated) node.nodeValue = translated;
  }
  for (const element of [root, ...root.querySelectorAll<HTMLElement>("*")]) {
    let source = attributeOriginals.get(element);
    if (!source) {
      source = new Map();
      attributeOriginals.set(element, source);
    }
    for (const attribute of attributes) {
      const current = element.getAttribute(attribute);
      if (current === null) continue;
      const previous = source.get(attribute);
      if (previous === undefined || !isLocalizedVariant(previous, current)) {
        source.set(attribute, current);
      }
      const translated = localize(source.get(attribute) || "", language);
      if (current !== translated) element.setAttribute(attribute, translated);
    }
  }
}

export function useScopedAdminTranslations(ref: RefObject<HTMLElement | null>, language: AdminLanguage) {
  useEffect(() => {
    const root = ref.current;
    if (!root) return;
    translateTree(root, language);
    const observer = new MutationObserver(() => translateTree(root, language));
    observer.observe(root, { childList: true, subtree: true, characterData: true, attributes: true, attributeFilter: [...attributes] });
    return () => observer.disconnect();
  });
}

export function adminPhraseKeys() {
  return { en: Object.keys(thaiPhrases), th: Object.keys(thaiPhrases) };
}
